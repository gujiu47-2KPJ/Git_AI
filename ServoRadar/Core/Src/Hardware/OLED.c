/* 显存缓冲区: 8页 x 128列 */
static uint8_t OLED_GRAM[OLED_PAGE_NUM][OLED_WIDTH];

/* 私有I2C句柄 */
static I2C_HandleTypeDef* s_hi2c = NULL;

/**
  * @brief  发送命令
  */
static void OLED_WriteCommand(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(s_hi2c, OLED_I2C_ADDR, buf, 2, HAL_MAX_DELAY);
}

/**
  * @brief  发送数据
  */
static void OLED_WriteData(uint8_t dat)
{
    uint8_t buf[2] = {0x40, dat};
    HAL_I2C_Master_Transmit(s_hi2c, OLED_I2C_ADDR, buf, 2, HAL_MAX_DELAY);
}

/**
  * @brief  设置显存坐标
  */
static void OLED_SetPos(uint8_t x, uint8_t y)
{
    OLED_WriteCommand(0xB0 | y);
    OLED_WriteCommand(((x & 0xF0) >> 4) | 0x10);
    OLED_WriteCommand(x & 0x0F);
}

/**
  * @brief  次方函数
  */
static uint32_t OLED_Pow(uint8_t m, uint8_t n)
{
    uint32_t result = 1;
    while(n--) result *= m;
    return result;
}

void OLED_Init(I2C_HandleTypeDef* hi2c)
{
    s_hi2c = hi2c;
    
    HAL_Delay(100);
    
    OLED_WriteCommand(0xAE); // Display OFF
    OLED_WriteCommand(0x20); // Set Memory Addressing Mode
    OLED_WriteCommand(0x10); // Page Addressing Mode
    OLED_WriteCommand(0xB0); // Set Page Start Address
    OLED_WriteCommand(0xC8); // Set COM Output Scan Direction
    OLED_WriteCommand(0x00); // Set Low Column Address
    OLED_WriteCommand(0x10); // Set High Column Address
    OLED_WriteCommand(0x40); // Set Display Start Line
    OLED_WriteCommand(0x81); // Set Contrast Control
    OLED_WriteCommand(0xFF);
    OLED_WriteCommand(0xA1); // Set Segment Re-map
    OLED_WriteCommand(0xA6); // Set Normal Display
    OLED_WriteCommand(0xA8); // Set Multiplex Ratio
    OLED_WriteCommand(0x3F); // 1/64 duty
    OLED_WriteCommand(0xD3); // Set Display Offset
    OLED_WriteCommand(0x00);
    OLED_WriteCommand(0xD5); // Set Display Clock Divide Ratio
    OLED_WriteCommand(0xF0);
    OLED_WriteCommand(0xD9); // Set Pre-charge Period
    OLED_WriteCommand(0x22);
    OLED_WriteCommand(0xDA); // Set COM Pins Hardware Configuration
    OLED_WriteCommand(0x12);
    OLED_WriteCommand(0xDB); // Set VCOMH Deselect Level
    OLED_WriteCommand(0x20);
    OLED_WriteCommand(0x8D); // Set DC-DC Enable
    OLED_WriteCommand(0x14);
    OLED_WriteCommand(0xAF); // Display ON
    
    OLED_Clear(hi2c);
    OLED_Refresh(hi2c);
}

void OLED_Clear(I2C_HandleTypeDef* hi2c)
{
    s_hi2c = hi2c;
    for(uint8_t i = 0; i < OLED_PAGE_NUM; i++)
    {
        for(uint8_t j = 0; j < OLED_WIDTH; j++)
        {
            OLED_GRAM[i][j] = 0x00;
        }
    }
}

void OLED_Refresh(I2C_HandleTypeDef* hi2c)
{
    s_hi2c = hi2c;
    for(uint8_t i = 0; i < OLED_PAGE_NUM; i++)
    {
        OLED_SetPos(0, i);
        for(uint8_t j = 0; j < OLED_WIDTH; j++)
        {
            OLED_WriteData(OLED_GRAM[i][j]);
        }
    }
}

void OLED_DrawPoint(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, uint8_t color)
{
    s_hi2c = hi2c;
    if(x > 127 || y > 63) return;
    
    uint8_t page = y / 8;
    uint8_t bit = y % 8;
    uint8_t mask = 1 << bit;
    
    if(color)
    {
        OLED_GRAM[page][x] |= mask;
    }
    else
    {
        OLED_GRAM[page][x] &= ~mask;
    }
}

void OLED_ShowChar(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, uint8_t chr, uint8_t size)
{
    s_hi2c = hi2c;
    if(x > 126 || y > 56) return;
    
    uint8_t index = chr - ' ';
    
    for(uint8_t i = 0; i < 6; i++)
    {
        for(uint8_t j = 0; j < 8; j++)
        {
            if(Font6x8[index][i] & (1 << j))
            {
                OLED_DrawPoint(hi2c, x + i, y + j, 1);
            }
            else
            {
                OLED_DrawPoint(hi2c, x + i, y + j, 0);
            }
        }
    }
}

void OLED_ShowString(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, char *str)
{
    s_hi2c = hi2c;
    uint8_t x0 = x;
    
    while(*str >= ' ' && *str <= '~')
    {
        if(x > 126)
        {
            x = x0;
            y += 8;
        }
        if(y > 56) return;
        
        OLED_ShowChar(hi2c, x, y, *str, 6);
        str++;
        x += 6;
    }
}

void OLED_ShowNum(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    s_hi2c = hi2c;
    uint8_t enshow = 0;
    
    for(uint8_t t = 0; t < len; t++)
    {
        uint8_t temp = (num / OLED_Pow(10, len - t - 1)) % 10;
        
        if(enshow == 0 && t < (len - 1))
        {
            if(temp == 0)
            {
                OLED_ShowChar(hi2c, x + t * 6, y, ' ', 6);
                continue;
            }
            else
            {
                enshow = 1;
            }
        }
        OLED_ShowChar(hi2c, x + t * 6, y, temp + '0', 6);
    }
}

void OLED_ShowFloat(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, float num, uint8_t decimal)
{
    s_hi2c = hi2c;
    char str[20];
    sprintf(str, "%.*f", decimal, num);
    OLED_ShowString(hi2c, x, y, str);
}

void OLED_ShowSignedNum(I2C_HandleTypeDef* hi2c, uint8_t x, uint8_t y, int32_t num, uint8_t len)
{
    s_hi2c = hi2c;
    if(num >= 0)
    {
        OLED_ShowChar(hi2c, x, y, '+', 6);
        OLED_ShowNum(hi2c, x + 6, y, num, len);
    }
    else
    {
        OLED_ShowChar(hi2c, x, y, '-', 6);
        OLED_ShowNum(hi2c, x + 6, y, -num, len);
    }
}